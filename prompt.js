function buildRecord(summary) {
  const lines = [];

  summary.byWeight.forEach(function (group) {
    lines.push("[" + group.title + "]");
    group.items.forEach(function (text) {
      lines.push("- " + text);
    });
    lines.push("");
  });

  if (summary.byGesture && summary.byGesture.length > 0) {
    lines.push("[돌아본 뒤 제가 정한 것]");
    summary.byGesture.forEach(function (group) {
      lines.push("  " + group.title + ":");
      group.items.forEach(function (text) {
        lines.push("  - " + text);
      });
    });
    lines.push("");
  }

  if (summary.present.length > 0) {
    lines.push("[그때는 없었지만, 지금의 나에게는 있는 것]");
    summary.present.forEach(function (text) {
      lines.push("- " + text);
    });
    lines.push("");
  }

  lines.push("[전체 상황]");
  lines.push(
    "- 모두 " + summary.pickedCount + "개를 골랐고, " +
    summary.categoryNames.join(", ") + " 영역에 걸쳐 있었습니다."
  );
  if (summary.mainCategory) {
    lines.push("- 상처가 가장 무겁게 모인 곳: " + summary.mainCategory);
  }
  if (summary.skippedCount > 0) {
    lines.push(
      "- 아직 말하고 싶지 않다며 건너뛴 것이 " + summary.skippedCount +
      "개 있습니다. (무엇인지는 밝히지 않았습니다)"
    );
  }

  if (summary.hesitated.length > 0) {
    lines.push("");
    lines.push("[지금 어떤지 답하기까지 한참 걸렸던 것]");
    summary.hesitated.forEach(function (text) {
      lines.push("- " + text);
    });
  }

  if (summary.slowPicks.length > 0) {
    lines.push("");
    lines.push("[고를 때 한참 머뭇거린 것]");
    summary.slowPicks.forEach(function (text) {
      lines.push("- " + text);
    });
  }

  if (summary.unpicked.length > 0) {
    lines.push("");
    lines.push("[골랐다가 도로 취소한 것]");
    summary.unpicked.forEach(function (text) {
      lines.push("- " + text);
    });
  }

  return lines.join("\n");
}

